-- ===========================================================================
-- Log the one path that was never logged: a teacher's own visit.
--
-- The proof fingerprint is not being learned on a real Windows launch, though
-- every part of it works when driven by hand. The learning condition is
--
--   v_admin and v_via_seb and v_proof is not null
--
-- and we cannot see which of the three is false, because seb_log() is only
-- called for students. So a teacher's visit now records exactly what get_exam
-- saw, and the next launch will say which term fails instead of leaving us to
-- guess a third time.
--
--   Supabase Dashboard -> SQL Editor -> paste -> Run
--
-- Idempotent: re-running it is safe. Needs 0028 first.
-- ===========================================================================

create or replace function public.get_exam(p_test_id uuid, p_seb_api boolean default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email   text := auth.jwt() ->> 'email';
  v_admin   boolean := public.is_admin();
  v_via_seb boolean := public.request_is_seb();
  v_key_ok  boolean := false;
  v_fp      text;
  v_stored  text;
  v_proof   text;
  v_stored_proof text;
  s         public.test_lockdown%rowtype;
  t         public.tests%rowtype;
  v_started timestamptz;
  v_ends    timestamptz;
  v_test    jsonb;
begin
  if v_email is null then
    raise exception 'You must be signed in to open a test.';
  end if;

  select * into t from public.tests where id = p_test_id;
  if not found then
    return jsonb_build_object('state', 'not_found');
  end if;

  v_test := jsonb_build_object(
    'id', t.id,
    'title', t.title,
    'subject', t.subject,
    'kind', t.kind,
    'duration_minutes', t.duration_minutes,
    'opens_at', t.opens_at,
    'closes_at', t.closes_at,
    'requires_seb', t.requires_seb,
    -- So the paper can tell students what a wrong answer costs.
    'negative_marking', t.negative_marking
  );

  -- Drafts are invisible to students; an admin may preview one, and doing so
  -- must not start a clock or leave an attempt row behind.
  if t.status <> 'published' then
    if not v_admin then
      return jsonb_build_object('state', 'not_released', 'test', v_test);
    end if;
    return jsonb_build_object(
      'state', 'preview',
      'test', v_test,
      'server_time', now(),
      'questions', public.exam_questions(p_test_id)
    );
  end if;

  -- This function runs as its owner and so is not filtered by the policy on
  -- tests. A student with a direct link would otherwise walk straight past it.
  if t.audience = 'selected' and not v_admin and not exists (
    select 1 from public.test_audience a
    where a.test_id = p_test_id and lower(a.email) = lower(v_email)
  ) then
    return jsonb_build_object('state', 'not_assigned', 'test', v_test);
  end if;

  if not v_admin and exists (select 1 from public.results r
              where r.test_id = p_test_id and r.email = v_email) then
    return jsonb_build_object('state', 'already_attempted', 'test', v_test,
                              'already_attempted', true);
  end if;

  -- Checked before the deadline and before any attempt is created, so opening
  -- the page early cannot start a clock the student is not entitled to yet.
  if not v_admin and t.opens_at is not null and now() < t.opens_at then
    return jsonb_build_object('state', 'not_open_yet', 'test', v_test,
                              'opens_at', t.opens_at, 'server_time', now());
  end if;

  if not v_admin and t.closes_at is not null and now() > t.closes_at then
    return jsonb_build_object('state', 'closed', 'test', v_test);
  end if;

  -- The Safe Exam Browser rule. Placed after the informational states, so a
  -- student in the wrong browser still learns that a test is closed or already
  -- done, but before the paper is handed over and -- crucially -- before the
  -- attempt row exists, so opening the link in Chrome cannot start their clock.
  -- Two questions, not one.
  --
  --   1. Does the browser SAY it is Safe Exam Browser? That is the user agent,
  --      and a student can forge it in a minute from Chrome's dev tools.
  --   2. Can it PROVE it? SEB hashes each request URL together with its keys
  --      and sends the digests as headers. Faking the user agent sends none of
  --      them, and the keys themselves never travel.
  --
  -- Nothing here is typed in by a teacher. The first time a teacher opens the
  -- paper inside SEB, the digest their SEB sends is remembered as this test's
  -- fingerprint, and every student is then held to it. A test nobody has ever
  -- opened in SEB keeps the old behaviour exactly, so this can never lock a
  -- hall out of a paper that was never set up.
  if t.requires_seb then
    -- Kept in test_lockdown, not on tests: students may read their own test
    -- row, and a fingerprint they can read is a fingerprint they can replay.
    select * into s from public.test_lockdown where test_id = p_test_id;

    -- Two independent sources of proof, belonging to two different URLs and
    -- therefore never comparable with each other:
    --   v_fp    the digest on THIS request, if SEB attaches keys cross-origin
    --   v_proof what SEB presented to api/seb-verify on the portal's own domain
    -- Windows SEB supplies only the second; macOS supplies both.
    v_fp := public.seb_fingerprint_seen();
    v_proof := public.seb_proof_of(p_test_id, v_email);
    v_stored := s.seb_fingerprint;
    v_stored_proof := s.seb_proof_fingerprint;
    v_key_ok := public.seb_key_ok(s.seb_browser_exam_key, s.seb_config_key);

    -- Re-learned on every teacher visit, not just the first, so upgrading SEB
    -- or changing the config heals itself the next time a teacher looks.
    if v_admin and v_via_seb and v_fp is not null then
      insert into public.test_lockdown (test_id, seb_fingerprint, seb_fingerprint_at, seb_fingerprint_by)
      values (p_test_id, v_fp, now(), v_email)
      on conflict (test_id) do update
        set seb_fingerprint = excluded.seb_fingerprint,
            seb_fingerprint_at = excluded.seb_fingerprint_at,
            seb_fingerprint_by = excluded.seb_fingerprint_by,
            updated_at = now();
      v_stored := v_fp;
    end if;

    -- Learned separately, because it is a digest of a different URL. A teacher
    -- on Windows teaches this one and nothing else, which is the whole point.
    if v_admin then
      perform public.seb_log(p_test_id, v_email,
        'teacher_visit via_seb=' || v_via_seb
          || ' direct=' || (v_fp is not null)
          || ' proof=' || (v_proof is not null)
          || ' stored_proof=' || (v_stored_proof is not null),
        v_stored_proof);
    end if;

    if v_admin and v_via_seb and v_proof is not null then
      insert into public.test_lockdown (test_id, seb_proof_fingerprint, seb_proof_at,
                                        seb_fingerprint_by)
      values (p_test_id, v_proof, now(), v_email)
      on conflict (test_id) do update
        set seb_proof_fingerprint = excluded.seb_proof_fingerprint,
            seb_proof_at = excluded.seb_proof_at,
            seb_fingerprint_by = excluded.seb_fingerprint_by,
            updated_at = now();
      v_stored_proof := v_proof;
    end if;
  end if;

  if t.requires_seb and not v_admin then
    if not v_via_seb then
      perform public.seb_log(p_test_id, v_email, 'not_seb', v_stored);
      return jsonb_build_object(
        'state', 'seb_required',
        'reason', 'not_seb',
        'test', v_test,
        'seb_config_url', t.seb_config_url,
        -- Returned so a genuine SEB that is not being recognised can be
        -- diagnosed from a screenshot rather than guessed at.
        'user_agent', left(public.request_user_agent(), 300)
      );
    end if;

    -- An out-of-date Safe Exam Browser is the usual reason the proof headers
    -- never arrive. Checked before the fingerprint, so such a machine is told
    -- plainly to update rather than left with "could not be verified", which
    -- says nothing anyone can act on.
    --
    -- A user agent proves nothing -- a student can write whatever they like in
    -- it -- so this refuses honest machines that need updating, and is not a
    -- security control. An unreadable version is never refused.
    if t.seb_min_version is not null
       and public.version_lt(
             public.seb_version_of(public.request_user_agent()), t.seb_min_version)
    then
      perform public.seb_log(p_test_id, v_email, 'outdated', v_stored);
      return jsonb_build_object(
        'state', 'seb_outdated',
        'test', v_test,
        'found_version', public.seb_version_of(public.request_user_agent()),
        'required_version', t.seb_min_version,
        'seb_config_url', t.seb_config_url,
        'user_agent', left(public.request_user_agent(), 300)
      );
    end if;

    -- The strongest proof this test has to offer, in order: a key a teacher
    -- pasted, else the fingerprint learned from a teacher's own SEB.
    if coalesce(nullif(s.seb_browser_exam_key, ''),
                nullif(s.seb_config_key, '')) is not null then
      if not v_key_ok and t.seb_enforcement in ('auto', 'strict') then
        perform public.seb_log(p_test_id, v_email, 'key_mismatch', v_stored);
        return jsonb_build_object(
          'state', 'seb_required', 'reason', 'key_mismatch', 'test', v_test,
          'seb_config_url', t.seb_config_url,
          'user_agent', left(public.request_user_agent(), 300)
        );
      end if;

    elsif v_stored is not null or v_stored_proof is not null then
      -- Either route is proof enough, and each is only ever compared with its
      -- own kind. A machine whose SEB does not reach Supabase directly still
      -- gets in on the strength of what it showed the endpoint.
      v_key_ok := (v_fp is not null and v_fp = v_stored)
               or (v_proof is not null and v_proof = v_stored_proof);

      if not v_key_ok and t.seb_enforcement in ('auto', 'strict') then
        perform public.seb_log(p_test_id, v_email, 'fingerprint_mismatch',
                               coalesce(v_stored, v_stored_proof));
        return jsonb_build_object(
          'state', 'seb_required', 'reason', 'key_mismatch', 'test', v_test,
          'seb_config_url', t.seb_config_url,
          'user_agent', left(public.request_user_agent(), 300)
        );
      end if;

    elsif t.seb_enforcement = 'strict' then
      -- Strict was asked for and nothing can prove anything yet.
      perform public.seb_log(p_test_id, v_email, 'key_not_configured', v_stored);
      return jsonb_build_object(
        'state', 'seb_required', 'reason', 'key_not_configured', 'test', v_test,
        'seb_config_url', t.seb_config_url,
        'user_agent', left(public.request_user_agent(), 300)
      );
    end if;
  end if;

  if t.requires_seb and not v_admin then
    perform public.seb_log(p_test_id, v_email, 'verified', v_stored);
  end if;

  -- A link test is taken elsewhere; hand back the address, nothing more.
  if t.kind = 'link' then
    return jsonb_build_object('state', 'external', 'test', v_test,
                              'form_url', t.form_url, 'server_time', now());
  end if;

  -- A teacher opening a published paper is inspecting it, not sitting it.
  -- Returning here means no attempt row, no clock, and nothing that can reach
  -- the mark list -- which is what makes it safe to open a test purely to
  -- teach it what a genuine Safe Exam Browser looks like.
  --
  -- The fingerprint above has already been learned by this point, so the whole
  -- setup costs a teacher one look at the paper and nothing else.
  if v_admin then
    return jsonb_build_object(
      'state', 'preview',
      'test', v_test,
      'server_time', now(),
      'questions', public.exam_questions(p_test_id)
    );
  end if;

  -- Starts the clock on first open. ON CONFLICT DO NOTHING is what makes a
  -- reload harmless: the original started_at -- and the original record of
  -- which browser opened it -- survive.
  insert into public.exam_attempts (test_id, email, via_seb, seb_api, user_agent, seb_key_verified)
  values (p_test_id, v_email, v_via_seb, p_seb_api, left(public.request_user_agent(), 500), v_key_ok)
  on conflict (test_id, email) do nothing;

  select started_at into v_started
  from public.exam_attempts
  where test_id = p_test_id and email = v_email;

  v_ends := public.exam_ends_at(v_started, t.duration_minutes, t.closes_at);

  if v_ends is not null and now() > v_ends then
    return jsonb_build_object('state', 'time_up', 'test', v_test);
  end if;

  return jsonb_build_object(
    'state', 'open',
    'test', v_test,
    'already_attempted', false,
    -- The browser's own clock is not trusted: it anchors its countdown to
    -- these two values and measures elapsed time from there.
    'server_time', now(),
    'started_at', v_started,
    'ends_at', v_ends,
    'questions', public.exam_questions(p_test_id)
  );
end;
$$;

revoke all on function public.get_exam(uuid, boolean) from public, anon;
grant execute on function public.get_exam(uuid, boolean) to authenticated;

notify pgrst, 'reload schema';


-- #########################################################################
-- ## 0032_learn_proof_at_source.sql
-- #########################################################################

-- ===========================================================================
-- Learn the proof fingerprint where it is observed, not one request later.
--
-- The proof was being recorded correctly and then not learned. Everything
-- worked when driven by hand and failed on a real launch, three times over,
-- because the learning lived in get_exam() and so depended on a chain of
-- circumstances holding:
--
--   * a second request arriving afterwards,
--   * in the right order,
--   * carrying a user agent Postgres still recognised as SEB,
--   * within the proof's thirty-minute window.
--
-- That is four ways to fail for something that should not be able to fail at
-- all. api/seb-verify already knows the test, the teacher and the digest, in
-- one transaction, with the SEB keys in its hands. So it learns the fingerprint
-- itself, and get_exam() merely reads what was stored.
--
-- Dropping the user-agent condition loses nothing: the presence of a valid
-- exam-key digest is far stronger evidence of a genuine SEB than a user agent,
-- which anyone can type. The digest is the evidence; the string was decoration.
--
--   Supabase Dashboard -> SQL Editor -> paste -> Run
--
-- Idempotent: re-running it is safe. Needs 0028 first.
-- ===========================================================================

create or replace function public.record_seb_proof(
  p_secret text,
  p_test_id uuid,
  p_config_key_hash text,
  p_request_hash text,
  p_user_agent text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email  text := auth.jwt() ->> 'email';
  v_secret text;
  v_digest text;
begin
  if v_email is null then
    return false;
  end if;

  select value into v_secret from public.app_secrets where name = 'seb_proof_secret';

  -- Not configured yet, or the wrong secret: record nothing and say so. The
  -- caller learns only true/false, never the secret itself.
  if v_secret is null or p_secret is null or p_secret <> v_secret then
    return false;
  end if;

  -- The Config Key digest is preferred because it depends only on the exam
  -- configuration, so it survives a SEB version upgrade.
  v_digest := coalesce(nullif(p_config_key_hash, ''), nullif(p_request_hash, ''));

  -- Nothing to record is not an error: a browser that sent no keys simply has
  -- no proof to offer, and the exam gate decides what that means.
  if v_digest is null then
    return false;
  end if;

  insert into public.seb_proofs (test_id, email, config_key_hash, request_hash, user_agent)
  values (p_test_id, v_email, nullif(p_config_key_hash, ''), nullif(p_request_hash, ''),
          left(p_user_agent, 500))
  on conflict (test_id, email) do update
    set config_key_hash = excluded.config_key_hash,
        request_hash = excluded.request_hash,
        user_agent = excluded.user_agent,
        seen_at = now();

  -- A teacher's own SEB is what a test learns from, and this is the moment to
  -- learn it: same transaction, digest in hand, nothing left to go wrong
  -- afterwards. Re-learned on every visit, so changing the config or upgrading
  -- SEB heals itself the next time a teacher opens the paper.
  if public.is_admin() then
    insert into public.test_lockdown (test_id, seb_proof_fingerprint, seb_proof_at,
                                      seb_fingerprint_by)
    values (p_test_id, v_digest, now(), v_email)
    on conflict (test_id) do update
      set seb_proof_fingerprint = excluded.seb_proof_fingerprint,
          seb_proof_at = excluded.seb_proof_at,
          seb_fingerprint_by = excluded.seb_fingerprint_by,
          updated_at = now();
  end if;

  return true;
end;
$$;

revoke all on function public.record_seb_proof(text, uuid, text, text, text) from public, anon;
grant execute on function public.record_seb_proof(text, uuid, text, text, text) to authenticated;

notify pgrst, 'reload schema';


-- #########################################################################
-- ## 0033_submit_accepts_proof.sql
-- #########################################################################

-- ===========================================================================
-- SERIOUS FIX -- a Windows student could sit a paper and then not hand it in.
--
-- get_exam() learned about the proof route in 0028. submit_exam() did not. It
-- still asked only whether SEB keys were attached to THIS request:
--
--   and v_fp is null            -- always true on Windows
--   and not v_key_ok
--
-- Windows SEB attaches its keys to this site's own domain and never to the
-- database, so v_fp is null there by design. With a fingerprint stored, a
-- Windows student could therefore open the paper -- get_exam admits them
-- correctly via their proof -- work through it, and be refused at the one
-- moment that cannot be retried:
--
--   "Safe Exam Browser could not be verified, so this paper cannot be
--    submitted."
--
-- Three hours of work, gone. That is the worst failure this app could have,
-- and it was mine: I taught one half of the pair about the new route and left
-- the other behind.
--
-- Now any one of four proofs is enough to hand a paper in:
--
--   1. the attempt was verified when the paper was opened   <- the decisive one
--   2. SEB keys on this very request                        (macOS)
--   3. a recent proof shown to api/seb-verify               (Windows)
--   4. a pasted Browser Exam Key that checks out
--
-- The first is what makes this safe to relax: a student who was let in
-- legitimately must never be prevented from handing in. To use it the check
-- had to move below the point where the attempt is read, which is also a
-- better place for it -- "you already submitted" and "open it first" are now
-- answered before any talk of browsers.
--
--   Supabase Dashboard -> SQL Editor -> paste -> Run
--
-- Idempotent: re-running it is safe. Needs 0028 first.
-- ===========================================================================

create or replace function public.submit_exam(p_test_id uuid, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email     text := auth.jwt() ->> 'email';
  v_admin     boolean := public.is_admin();
  v_via_seb   boolean := public.request_is_seb();
  v_key_ok    boolean := false;
  v_fp        text;
  s           public.test_lockdown%rowtype;
  v_att_key   boolean;
  v_total     numeric := 0;
  v_score     numeric := 0;
  v_bonus     numeric := 0;
  v_penalty   numeric := 0;
  v_lost      numeric := 0;
  v_pct       numeric;
  t           public.tests%rowtype;
  v_started   timestamptz;
  v_ends      timestamptz;
  v_att_seb   boolean;
  v_seb_api   boolean;
  v_result_id uuid;
  q           record;
  v_given     jsonb;
  v_number    numeric;
  v_expected  text[];
  v_actual    text[];
  v_correct   boolean;
  v_detail    jsonb := '[]'::jsonb;
begin
  if v_email is null then
    raise exception 'You must be signed in to submit a test.';
  end if;

  select * into t from public.tests where id = p_test_id;
  if not found then
    raise exception 'That test no longer exists.';
  end if;

  if t.status <> 'published' then
    raise exception 'This test has not been released.';
  end if;

  if t.requires_seb then
    select * into s from public.test_lockdown where test_id = p_test_id;

    v_fp := public.seb_fingerprint_seen();
    v_key_ok := public.seb_key_ok(s.seb_browser_exam_key, s.seb_config_key);
  end if;

  if exists (
    select 1 from public.results where test_id = p_test_id and email = v_email
  ) then
    raise exception 'You have already submitted this test.';
  end if;

  select started_at, via_seb, seb_api, seb_key_verified
    into v_started, v_att_seb, v_seb_api, v_att_key
  from public.exam_attempts
  where test_id = p_test_id and email = v_email;

  if v_started is null then
    raise exception 'Open the test before submitting it.';
  end if;

  -- The lockdown rule at hand-in. Deliberately placed AFTER the attempt is
  -- known, because the decisive fact is whether this paper was verified when it
  -- was handed over -- and that is recorded on the attempt.
  --
  -- Windows SEB attaches its keys only to this site's own domain, never to the
  -- database, so v_fp is always null there. Judging on v_fp alone meant a
  -- Windows student could open a paper, sit it for three hours, and then be
  -- refused at the moment of submission. Losing a finished paper is a far worse
  -- failure than any forgery this could catch, so any one of four proofs will do.
  if t.requires_seb and not v_admin then
    if not v_via_seb then
      raise exception 'This test must be submitted from Safe Exam Browser.';
    end if;

    if t.seb_enforcement in ('auto', 'strict')
       and (s.seb_fingerprint is not null
            or s.seb_proof_fingerprint is not null
            or coalesce(nullif(s.seb_browser_exam_key, ''),
                        nullif(s.seb_config_key, '')) is not null)
       -- verified when the paper was opened ...
       and not coalesce(v_att_key, false)
       -- ... or keys on this very request ...
       and v_fp is null
       -- ... or shown to api/seb-verify recently ...
       and public.seb_proof_of(p_test_id, v_email) is null
       -- ... or a pasted key that checks out.
       and not v_key_ok
    then
      raise exception 'Safe Exam Browser could not be verified, so this paper cannot be submitted. Please tell your teacher.'
        using errcode = '42501';
    end if;
  end if;

  -- Marks lost per wrong answer, as a fraction of that question's marks:
  -- 0.25 is the familiar +4 / -1.
  v_penalty := coalesce(t.negative_marking, 0);

  v_ends := public.exam_ends_at(v_started, t.duration_minutes, t.closes_at);

  if v_ends is not null and now() > v_ends + interval '1 minute' then
    raise exception 'Time is up for this test, so it can no longer be submitted.';
  end if;

  for q in
    select * from public.questions where test_id = p_test_id
    order by position, created_at
  loop
    -- Bonus questions add to the score but never to the total: missing one
    -- costs nothing.
    if not q.is_bonus then
      v_total := v_total + q.points;
    end if;
    v_given := p_answers -> q.id::text;
    v_correct := false;

    if v_given is not null and v_given <> 'null'::jsonb then
      if q.type = 'text' then
        v_correct := jsonb_typeof(v_given) = 'string' and exists (
          select 1
          from jsonb_array_elements_text(q.answer_key) k
          where lower(btrim(k)) = lower(btrim(v_given #>> '{}'))
        );
      elsif q.type = 'numerical' then
        -- Compared as numbers, so 2.50, 2.5 and +2.5 are the same answer.
        v_number := case
          when jsonb_typeof(v_given) in ('string', 'number')
          then public.parse_decimal(v_given #>> '{}')
        end;
        v_correct := v_number is not null and exists (
          select 1
          from jsonb_array_elements_text(q.answer_key) k
          where public.parse_decimal(k) is not null
            and abs(v_number - public.parse_decimal(k)) <= coalesce(q.tolerance, 0)
        );
      elsif jsonb_typeof(v_given) = 'array' then
        select array(select jsonb_array_elements_text(q.answer_key) order by 1)
          into v_expected;
        select array(select distinct jsonb_array_elements_text(v_given) order by 1)
          into v_actual;

        v_correct := v_expected = v_actual;
      end if;
    end if;

    if v_correct then
      if q.is_bonus then
        v_bonus := v_bonus + q.points;
      else
        v_score := v_score + q.points;
      end if;
    elsif v_penalty > 0
      and not q.is_bonus
      -- Only a real attempt is penalised, and never a typed answer: losing
      -- marks to a spelling slip is not what negative marking is for.
      and q.type in ('single', 'multiple', 'numerical')
      and v_given is not null and v_given <> 'null'::jsonb
      and not (jsonb_typeof(v_given) = 'array' and jsonb_array_length(v_given) = 0)
      and not (jsonb_typeof(v_given) = 'string' and btrim(v_given #>> '{}') = '')
    then
      v_lost := v_lost + q.points * v_penalty;
    end if;

    v_detail := v_detail || jsonb_build_object(
      'q', q.id,
      'type', q.type,
      'points', q.points,
      'bonus', q.is_bonus,
      'earned', case
        when v_correct then q.points
        when v_penalty > 0 and not q.is_bonus and q.type in ('single', 'multiple', 'numerical')
             and v_given is not null and v_given <> 'null'::jsonb
        then -(q.points * v_penalty)
        else 0
      end,
      'given', coalesce(v_given, 'null'::jsonb),
      'correct', v_correct
    );
  end loop;

  if v_total = 0 then
    raise exception 'This test has no marked questions yet.';
  end if;

  -- Penalties, then bonus marks. A paper cannot score below zero or above
  -- full marks.
  v_score := greatest(least(v_score - v_lost + v_bonus, v_total), 0);
  v_pct := round((v_score / v_total) * 100);

  insert into public.results (test_id, email, score, total, percentage, attempted_at,
                              via_seb, seb_api, seb_key_verified)
  values (p_test_id, v_email, v_score, v_total, v_pct, now(),
          v_via_seb and coalesce(v_att_seb, v_via_seb), v_seb_api,
          -- True only if the key checked out when the paper was opened AND
          -- when it was handed in.
          coalesce(v_att_key, v_key_ok))
  returning id into v_result_id;

  insert into public.result_details (result_id, detail)
  values (v_result_id, v_detail);

  update public.exam_attempts
  set submitted_at = now()
  where test_id = p_test_id and email = v_email;

  return jsonb_build_object('score', v_score, 'total', v_total, 'percentage', v_pct,
                            'bonus', v_bonus, 'lost', v_lost);
end;
$$;

revoke all on function public.submit_exam(uuid, jsonb) from public, anon;
grant execute on function public.submit_exam(uuid, jsonb) to authenticated;

notify pgrst, 'reload schema';


-- #########################################################################
-- ## 0034_one_route.sql
-- #########################################################################

-- ===========================================================================
-- Collapse the lockdown check to one route, and delete the rest.
--
-- Answering "is this really Safe Exam Browser?" grew to thirteen migrations and
-- four thousand lines -- as much as the whole rest of the app. Most of that was
-- not the problem being hard. It was two mechanisms kept side by side:
--
--   the DIRECT route   keys read from the request that reaches the database
--   the PROOF route    keys observed by api/seb-verify, on this site's domain
--
-- The digests belong to different URLs, so they can never be compared with each
-- other. Three separate bugs came from exactly that: an indicator reading the
-- direct value when only the proof existed, and a submission gate that checked
-- the direct value on a platform that never sends it -- which would have thrown
-- away a finished paper.
--
-- Only the proof route works everywhere, so only the proof route survives.
--
-- Also deleted: the minimum-version check from 0026. It was built on the belief
-- that an old SEB was the cause, and the logging then showed the opposite --
-- SEB 3.10 on Windows sent nothing while 3.7 on macOS sent everything. A signal
-- that points the wrong way is worse than none, and it had already blocked a
-- working machine once.
--
-- And the pasted Browser Exam Key from 0021: the automatic fingerprint does the
-- same job without anybody typing a 64-character string.
--
-- WHAT THIS COSTS: every test must be shown a teacher's SEB once more, because
-- the direct fingerprints are being dropped. Open each protected test in SEB as
-- a teacher after running this. A test that has not been shown one is not
-- enforced -- it is never locked shut.
--
--   Supabase Dashboard -> SQL Editor -> paste -> Run
--
-- Idempotent: re-running it is safe. Needs 0033 first.
-- ===========================================================================

-- --- 1. the exam functions, on one route ------------------------------------

create or replace function public.get_exam(p_test_id uuid, p_seb_api boolean default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email   text := auth.jwt() ->> 'email';
  v_admin   boolean := public.is_admin();
  v_via_seb boolean := public.request_is_seb();
  v_key_ok  boolean := false;
  v_proof   text;
  v_stored  text;
  s         public.test_lockdown%rowtype;
  t         public.tests%rowtype;
  v_started timestamptz;
  v_ends    timestamptz;
  v_test    jsonb;
begin
  if v_email is null then
    raise exception 'You must be signed in to open a test.';
  end if;

  select * into t from public.tests where id = p_test_id;
  if not found then
    return jsonb_build_object('state', 'not_found');
  end if;

  v_test := jsonb_build_object(
    'id', t.id,
    'title', t.title,
    'subject', t.subject,
    'kind', t.kind,
    'duration_minutes', t.duration_minutes,
    'opens_at', t.opens_at,
    'closes_at', t.closes_at,
    'requires_seb', t.requires_seb,
    -- So the paper can tell students what a wrong answer costs.
    'negative_marking', t.negative_marking
  );

  -- Drafts are invisible to students; an admin may preview one, and doing so
  -- must not start a clock or leave an attempt row behind.
  if t.status <> 'published' then
    if not v_admin then
      return jsonb_build_object('state', 'not_released', 'test', v_test);
    end if;
    return jsonb_build_object(
      'state', 'preview',
      'test', v_test,
      'server_time', now(),
      'questions', public.exam_questions(p_test_id)
    );
  end if;

  -- This function runs as its owner and so is not filtered by the policy on
  -- tests. A student with a direct link would otherwise walk straight past it.
  if t.audience = 'selected' and not v_admin and not exists (
    select 1 from public.test_audience a
    where a.test_id = p_test_id and lower(a.email) = lower(v_email)
  ) then
    return jsonb_build_object('state', 'not_assigned', 'test', v_test);
  end if;

  if not v_admin and exists (select 1 from public.results r
              where r.test_id = p_test_id and r.email = v_email) then
    return jsonb_build_object('state', 'already_attempted', 'test', v_test,
                              'already_attempted', true);
  end if;

  -- Checked before the deadline and before any attempt is created, so opening
  -- the page early cannot start a clock the student is not entitled to yet.
  if not v_admin and t.opens_at is not null and now() < t.opens_at then
    return jsonb_build_object('state', 'not_open_yet', 'test', v_test,
                              'opens_at', t.opens_at, 'server_time', now());
  end if;

  if not v_admin and t.closes_at is not null and now() > t.closes_at then
    return jsonb_build_object('state', 'closed', 'test', v_test);
  end if;

  -- The Safe Exam Browser rule.
  --
  -- SEB attaches its exam keys to requests for this site's own domain, and some
  -- builds send them nowhere else -- never to the database. So the keys are
  -- observed by api/seb-verify, which records what it saw, and this function
  -- reads the recording. One route, on every platform.
  --
  -- The fingerprint is taught by record_seb_proof() the moment a teacher's own
  -- SEB presents its keys. Nothing is learned here, and nothing needs to be: a
  -- second request having to arrive afterwards, in the right order, carrying a
  -- user agent still recognised as SEB, was exactly the fragility that made
  -- this fail three times over.
  --
  -- A test no teacher has opened in SEB has no fingerprint and behaves as it
  -- always did, so this can never lock a hall out of a paper never set up.
  if t.requires_seb then
    select * into s from public.test_lockdown where test_id = p_test_id;

    v_proof := public.seb_proof_of(p_test_id, v_email);
    v_stored := s.seb_proof_fingerprint;
    v_key_ok := v_proof is not null and v_proof = v_stored;

    if v_admin then
      perform public.seb_log(p_test_id, v_email,
        'teacher_visit proof=' || (v_proof is not null)
          || ' stored=' || (v_stored is not null), v_stored);
    end if;
  end if;

  if t.requires_seb and not v_admin then
    if not v_via_seb then
      perform public.seb_log(p_test_id, v_email, 'not_seb', v_stored);
      return jsonb_build_object(
        'state', 'seb_required',
        'reason', 'not_seb',
        'test', v_test,
        'seb_config_url', t.seb_config_url,
        -- Returned so a genuine SEB that is not being recognised can be
        -- diagnosed from a screenshot rather than guessed at.
        'user_agent', left(public.request_user_agent(), 300)
      );
    end if;

    if v_stored is not null then
      if not v_key_ok and t.seb_enforcement in ('auto', 'strict') then
        perform public.seb_log(p_test_id, v_email, 'fingerprint_mismatch', v_stored);
        return jsonb_build_object(
          'state', 'seb_required', 'reason', 'key_mismatch', 'test', v_test,
          'seb_config_url', t.seb_config_url,
          'user_agent', left(public.request_user_agent(), 300)
        );
      end if;

    elsif t.seb_enforcement = 'strict' then
      -- Strict was asked for and nothing can prove anything yet.
      perform public.seb_log(p_test_id, v_email, 'key_not_configured', v_stored);
      return jsonb_build_object(
        'state', 'seb_required', 'reason', 'key_not_configured', 'test', v_test,
        'seb_config_url', t.seb_config_url,
        'user_agent', left(public.request_user_agent(), 300)
      );
    end if;

    perform public.seb_log(p_test_id, v_email, 'verified', v_stored);
  end if;

  -- A link test is taken elsewhere; hand back the address, nothing more.
  if t.kind = 'link' then
    return jsonb_build_object('state', 'external', 'test', v_test,
                              'form_url', t.form_url, 'server_time', now());
  end if;

  -- A teacher opening a published paper is inspecting it, not sitting it.
  -- Returning here means no attempt row, no clock, and nothing that can reach
  -- the mark list -- which is what makes it safe to open a test purely to
  -- teach it what a genuine Safe Exam Browser looks like.
  --
  -- The fingerprint above has already been learned by this point, so the whole
  -- setup costs a teacher one look at the paper and nothing else.
  if v_admin then
    return jsonb_build_object(
      'state', 'preview',
      'test', v_test,
      'server_time', now(),
      'questions', public.exam_questions(p_test_id)
    );
  end if;

  -- Starts the clock on first open. ON CONFLICT DO NOTHING is what makes a
  -- reload harmless: the original started_at -- and the original record of
  -- which browser opened it -- survive.
  insert into public.exam_attempts (test_id, email, via_seb, seb_api, user_agent, seb_key_verified)
  values (p_test_id, v_email, v_via_seb, p_seb_api, left(public.request_user_agent(), 500), v_key_ok)
  on conflict (test_id, email) do nothing;

  select started_at into v_started
  from public.exam_attempts
  where test_id = p_test_id and email = v_email;

  v_ends := public.exam_ends_at(v_started, t.duration_minutes, t.closes_at);

  if v_ends is not null and now() > v_ends then
    return jsonb_build_object('state', 'time_up', 'test', v_test);
  end if;

  return jsonb_build_object(
    'state', 'open',
    'test', v_test,
    'already_attempted', false,
    -- The browser's own clock is not trusted: it anchors its countdown to
    -- these two values and measures elapsed time from there.
    'server_time', now(),
    'started_at', v_started,
    'ends_at', v_ends,
    'questions', public.exam_questions(p_test_id)
  );
end;
$$;

revoke all on function public.get_exam(uuid, boolean) from public, anon;
grant execute on function public.get_exam(uuid, boolean) to authenticated;

create or replace function public.submit_exam(p_test_id uuid, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email     text := auth.jwt() ->> 'email';
  v_admin     boolean := public.is_admin();
  v_via_seb   boolean := public.request_is_seb();
  v_key_ok    boolean := false;
  v_proof     text;
  s           public.test_lockdown%rowtype;
  v_att_key   boolean;
  v_total     numeric := 0;
  v_score     numeric := 0;
  v_bonus     numeric := 0;
  v_penalty   numeric := 0;
  v_lost      numeric := 0;
  v_pct       numeric;
  t           public.tests%rowtype;
  v_started   timestamptz;
  v_ends      timestamptz;
  v_att_seb   boolean;
  v_seb_api   boolean;
  v_result_id uuid;
  q           record;
  v_given     jsonb;
  v_number    numeric;
  v_expected  text[];
  v_actual    text[];
  v_correct   boolean;
  v_detail    jsonb := '[]'::jsonb;
begin
  if v_email is null then
    raise exception 'You must be signed in to submit a test.';
  end if;

  select * into t from public.tests where id = p_test_id;
  if not found then
    raise exception 'That test no longer exists.';
  end if;

  if t.status <> 'published' then
    raise exception 'This test has not been released.';
  end if;

  if t.requires_seb then
    select * into s from public.test_lockdown where test_id = p_test_id;
  end if;

  if exists (
    select 1 from public.results where test_id = p_test_id and email = v_email
  ) then
    raise exception 'You have already submitted this test.';
  end if;

  select started_at, via_seb, seb_api, seb_key_verified
    into v_started, v_att_seb, v_seb_api, v_att_key
  from public.exam_attempts
  where test_id = p_test_id and email = v_email;

  if v_started is null then
    raise exception 'Open the test before submitting it.';
  end if;

  -- The lockdown rule at hand-in, placed after the attempt is known, because
  -- the decisive fact is whether this paper was verified when it was handed
  -- over -- and that is recorded on the attempt.
  --
  -- A student let in legitimately must never be prevented from handing in:
  -- losing a finished paper is a far worse failure than any forgery this could
  -- catch. So a verified open is enough on its own, and a fresh proof is
  -- accepted too, for a session that has been going a long time.
  if t.requires_seb and not v_admin then
    if not v_via_seb then
      raise exception 'This test must be submitted from Safe Exam Browser.';
    end if;

    v_proof := public.seb_proof_of(p_test_id, v_email);

    if t.seb_enforcement in ('auto', 'strict')
       and s.seb_proof_fingerprint is not null
       and not coalesce(v_att_key, false)
       and not (v_proof is not null and v_proof = s.seb_proof_fingerprint)
    then
      raise exception 'Safe Exam Browser could not be verified, so this paper cannot be submitted. Please tell your teacher.'
        using errcode = '42501';
    end if;
  end if;

  -- Marks lost per wrong answer, as a fraction of that question's marks:
  -- 0.25 is the familiar +4 / -1.
  v_penalty := coalesce(t.negative_marking, 0);

  v_ends := public.exam_ends_at(v_started, t.duration_minutes, t.closes_at);

  if v_ends is not null and now() > v_ends + interval '1 minute' then
    raise exception 'Time is up for this test, so it can no longer be submitted.';
  end if;

  for q in
    select * from public.questions where test_id = p_test_id
    order by position, created_at
  loop
    -- Bonus questions add to the score but never to the total: missing one
    -- costs nothing.
    if not q.is_bonus then
      v_total := v_total + q.points;
    end if;
    v_given := p_answers -> q.id::text;
    v_correct := false;

    if v_given is not null and v_given <> 'null'::jsonb then
      if q.type = 'text' then
        v_correct := jsonb_typeof(v_given) = 'string' and exists (
          select 1
          from jsonb_array_elements_text(q.answer_key) k
          where lower(btrim(k)) = lower(btrim(v_given #>> '{}'))
        );
      elsif q.type = 'numerical' then
        -- Compared as numbers, so 2.50, 2.5 and +2.5 are the same answer.
        v_number := case
          when jsonb_typeof(v_given) in ('string', 'number')
          then public.parse_decimal(v_given #>> '{}')
        end;
        v_correct := v_number is not null and exists (
          select 1
          from jsonb_array_elements_text(q.answer_key) k
          where public.parse_decimal(k) is not null
            and abs(v_number - public.parse_decimal(k)) <= coalesce(q.tolerance, 0)
        );
      elsif jsonb_typeof(v_given) = 'array' then
        select array(select jsonb_array_elements_text(q.answer_key) order by 1)
          into v_expected;
        select array(select distinct jsonb_array_elements_text(v_given) order by 1)
          into v_actual;

        v_correct := v_expected = v_actual;
      end if;
    end if;

    if v_correct then
      if q.is_bonus then
        v_bonus := v_bonus + q.points;
      else
        v_score := v_score + q.points;
      end if;
    elsif v_penalty > 0
      and not q.is_bonus
      -- Only a real attempt is penalised, and never a typed answer: losing
      -- marks to a spelling slip is not what negative marking is for.
      and q.type in ('single', 'multiple', 'numerical')
      and v_given is not null and v_given <> 'null'::jsonb
      and not (jsonb_typeof(v_given) = 'array' and jsonb_array_length(v_given) = 0)
      and not (jsonb_typeof(v_given) = 'string' and btrim(v_given #>> '{}') = '')
    then
      v_lost := v_lost + q.points * v_penalty;
    end if;

    v_detail := v_detail || jsonb_build_object(
      'q', q.id,
      'type', q.type,
      'points', q.points,
      'bonus', q.is_bonus,
      'earned', case
        when v_correct then q.points
        when v_penalty > 0 and not q.is_bonus and q.type in ('single', 'multiple', 'numerical')
             and v_given is not null and v_given <> 'null'::jsonb
        then -(q.points * v_penalty)
        else 0
      end,
      'given', coalesce(v_given, 'null'::jsonb),
      'correct', v_correct
    );
  end loop;

  if v_total = 0 then
    raise exception 'This test has no marked questions yet.';
  end if;

  -- Penalties, then bonus marks. A paper cannot score below zero or above
  -- full marks.
  v_score := greatest(least(v_score - v_lost + v_bonus, v_total), 0);
  v_pct := round((v_score / v_total) * 100);

  insert into public.results (test_id, email, score, total, percentage, attempted_at,
                              via_seb, seb_api, seb_key_verified)
  values (p_test_id, v_email, v_score, v_total, v_pct, now(),
          v_via_seb and coalesce(v_att_seb, v_via_seb), v_seb_api,
          -- True only if the key checked out when the paper was opened AND
          -- when it was handed in.
          coalesce(v_att_key, v_key_ok))
  returning id into v_result_id;

  insert into public.result_details (result_id, detail)
  values (v_result_id, v_detail);

  update public.exam_attempts
  set submitted_at = now()
  where test_id = p_test_id and email = v_email;

  return jsonb_build_object('score', v_score, 'total', v_total, 'percentage', v_pct,
                            'bonus', v_bonus, 'lost', v_lost);
end;
$$;

revoke all on function public.submit_exam(uuid, jsonb) from public, anon;
grant execute on function public.submit_exam(uuid, jsonb) to authenticated;

-- --- 2. the teacher's panel, reporting the one route ------------------------

create or replace function public.seb_check(p_test_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  t       public.tests%rowtype;
  s       public.test_lockdown%rowtype;
  v_proof text;
begin
  perform public.require_admin();

  select * into t from public.tests where id = p_test_id;
  if not found then
    raise exception 'That test no longer exists.';
  end if;

  select * into s from public.test_lockdown where test_id = p_test_id;
  v_proof := public.seb_proof_of(p_test_id, auth.jwt() ->> 'email');

  return jsonb_build_object(
    'enforcement', t.seb_enforcement,
    'requires_seb', t.requires_seb,
    'looks_like_seb', public.request_is_seb(),
    'user_agent', left(public.request_user_agent(), 300),
    -- Did this browser show its keys to api/seb-verify?
    'proof_recorded', v_proof is not null,
    'proof_fingerprint_stored', s.seb_proof_fingerprint,
    'proof_learned_at', s.seb_proof_at,
    'verified', v_proof is not null and v_proof = s.seb_proof_fingerprint
  );
end;
$$;

revoke all on function public.seb_check(uuid) from public, anon;
grant execute on function public.seb_check(uuid) to authenticated;

-- --- 3. delete the direct route and the version check -----------------------

-- Dropped after the functions above stop referencing them, so this file can be
-- run in one go.
drop function if exists public.seb_fingerprint_seen();
drop function if exists public.seb_key_ok(text, text);
drop function if exists public.seb_hash_matches(text, text);
drop function if exists public.seb_candidate_urls();
drop function if exists public.seb_version_of(text);
drop function if exists public.version_lt(text, text);

alter table public.tests
  drop column if exists seb_min_version;

alter table public.test_lockdown
  drop column if exists seb_fingerprint,
  drop column if exists seb_fingerprint_at,
  drop column if exists seb_browser_exam_key,
  drop column if exists seb_config_key;

-- The log recorded both digests as separate columns; only one arrives now, and
-- seb_log() writes it as config_key_hash.
alter table public.seb_check_log
  drop column if exists request_hash;

-- seb_log() referenced the dropped request_header lookups for both digests.
create or replace function public.seb_log(
  p_test_id uuid,
  p_email text,
  p_outcome text,
  p_expected text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.seb_check_log (
    test_id, email, outcome, user_agent, config_key_hash, expected_fingerprint)
  values (
    p_test_id, p_email, p_outcome,
    left(public.request_user_agent(), 500),
    -- What this request carried, which on most platforms is nothing: the proof
    -- route is what counts, and `expected` shows what it was measured against.
    public.request_header('x-safeexambrowser-configkeyhash'),
    p_expected);
exception
  -- Diagnostics must never be the reason a student cannot sit a paper.
  when others then null;
end;
$$;

revoke all on function public.seb_log(uuid, text, text, text) from public, anon, authenticated;

