-- --- 3. recording a proof ----------------------------------------------------

-- Called by api/seb-verify with the student's own token, so the identity comes
-- from the JWT and cannot be chosen by the caller, plus the shared secret,
-- which proves the call came through the endpoint and not from the page.
create or replace function public.record_seb_proof(
  p_secret text,
  p_test_id uuid,
  p_config_key_hash text,
  p_request_hash text,
  p_user_agent text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email  text := auth.jwt() ->> 'email';
  v_secret text;
begin
  if v_email is null then
    return false;
  end if;

  select value into v_secret from public.app_secrets where name = 'seb_proof_secret';

  -- Not configured yet, or the wrong secret: record nothing and say so. The
  -- caller learns only true/false, never the secret itself.
  if v_secret is null or p_secret is null or p_secret <> v_secret then
    return false;
  end if;

  -- Nothing to record is not an error: a browser that sent no keys simply has
  -- no proof to offer, and the exam gate decides what that means.
  if coalesce(p_config_key_hash, '') = '' and coalesce(p_request_hash, '') = '' then
    return false;
  end if;

  insert into public.seb_proofs (test_id, email, config_key_hash, request_hash, user_agent)
  values (p_test_id, v_email, nullif(p_config_key_hash, ''), nullif(p_request_hash, ''),
          left(p_user_agent, 500))
  on conflict (test_id, email) do update
    set config_key_hash = excluded.config_key_hash,
        request_hash = excluded.request_hash,
        user_agent = excluded.user_agent,
        seen_at = now();

  return true;
end;
$$;

revoke all on function public.record_seb_proof(text, uuid, text, text, text) from public, anon;
grant execute on function public.record_seb_proof(text, uuid, text, text, text) to authenticated;

-- --- 4. reading a proof back --------------------------------------------------

-- The digest this student's SEB presented to the endpoint, if it did so
-- recently. Stale proofs are ignored so one verified launch cannot be used to
-- open a paper days later from somewhere else.
create or replace function public.seb_proof_of(p_test_id uuid, p_email text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(p.config_key_hash, p.request_hash)
  from public.seb_proofs p
  where p.test_id = p_test_id
    and p.email = p_email
    and p.seen_at > now() - interval '30 minutes';
$$;

revoke all on function public.seb_proof_of(uuid, text) from public, anon, authenticated;

