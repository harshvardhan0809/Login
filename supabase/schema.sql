-- ## 0028_seb_same_origin_proof.sql
-- #########################################################################

-- ===========================================================================
-- Verify Safe Exam Browser where it actually sends its keys.
--
-- What the logging in 0027 finally showed, from two real machines:
--
--   SEB 3.10.0 on Windows  ->  configkey MISSING, requesthash MISSING
--   SEB 3.7    on macOS    ->  configkey matches the stored fingerprint exactly
--
-- So the Mac attaches its exam keys to every request, including the
-- cross-origin ones to supabase.co, and the Windows build attaches them only
-- to the exam server's own domain. Reading the headers at Supabase therefore
-- works on one platform and silently fails on the other -- and the newer
-- version is the one that fails, which is why standardising on "latest" would
-- have made things worse rather than better.
--
-- The fix is to stop reading the headers somewhere SEB may not send them.
-- A small endpoint on the portal's own domain (api/seb-verify) is same-origin,
-- so every SEB sends its keys there. That endpoint records what it saw, and
-- this migration teaches get_exam() to read the recording instead.
--
-- Why a recording rather than a relayed header: anything the browser hands us
-- it can also fabricate. The endpoint runs on the server, holds a secret the
-- browser never sees, and is the only thing that can write a proof. A student
-- calling record_seb_proof() straight from the page has no secret and is
-- refused.
--
-- The digest is computed over the URL being requested, so a proof recorded at
-- api/seb-verify is a different value from a header seen at supabase.co. They
-- are therefore learned and compared as two separate fingerprints, never
-- against each other. Either one matching is proof enough, which keeps the Mac
-- working even if the endpoint is unreachable.
--
-- BEFORE THIS WORKS you must set the shared secret in two places:
--
--   1. Generate one:      openssl rand -hex 32
--   2. In this database:  select public.admin_set_seb_secret('<that value>');
--   3. In Vercel:         add it as the environment variable SEB_PROOF_SECRET
--
-- Until the secret is set, record_seb_proof() refuses everything and the
-- behaviour is exactly as it is today -- no lockout.
--
--   Supabase Dashboard -> SQL Editor -> paste -> Run
--
-- Idempotent: re-running it is safe. Needs 0027 first.
-- ===========================================================================

-- --- 1. a secret the browser never sees --------------------------------------

create table if not exists public.app_secrets (
  name text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

alter table public.app_secrets enable row level security;

-- No policies at all, and no privileges: nothing reachable through PostgREST
-- can read this, whoever they are. Only SECURITY DEFINER functions, which run
-- as the table's owner, can see inside it.
revoke all on public.app_secrets from anon, authenticated;

create or replace function public.admin_set_seb_secret(p_value text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.require_admin();

  if coalesce(btrim(p_value), '') = '' then
    raise exception 'The secret cannot be blank.';
  end if;
  if length(btrim(p_value)) < 32 then
    raise exception 'Use a longer secret — 32 characters at least. Try: openssl rand -hex 32';
  end if;

  insert into public.app_secrets (name, value)
  values ('seb_proof_secret', btrim(p_value))
  on conflict (name) do update
    set value = excluded.value, updated_at = now();
end;
$$;

revoke all on function public.admin_set_seb_secret(text) from public, anon;
grant execute on function public.admin_set_seb_secret(text) to authenticated;

